"""Write docs/model_cards.md: one card per model family plus a table of every completed run.

Usage:
    python -X utf8 -m src.make_model_cards

Reads completed run.json files only (no data, no inference). Rerun after new runs finish.
"""
from __future__ import annotations

import json

from src.common import ROOT

FAMILIES = ("ptbxl_v2", "ptbxl_v2_fixedgain", "ptbxl_signal", "ptbxl_cnn_lstm", "ptbxl_spatiotemporal", "ptbxl_hybrid_vit")
CARDS = {
    "PCA + LDA / PCA + linear SVM": "Classical baselines on PCA of the downsampled page; one fit each (no seeds). "
        "Hyperparameters chosen on validation by a frozen grid.",
    "CNN-only (cnn_pool)": "Shared 1,220-parameter lead-image CNN, mean over 70 feature columns, linear readout. "
        "1,705 parameters. Sees only local image regions; cannot relate the calibration pulse to the waveform.",
    "Wide CNN-only (cnn_pool_wide)": "Same CNN, per-column MLP 96-96-64 then column mean. 17,065 parameters: "
        "capacity of the sequence heads without column mixing (protocol amendment 3 Nov 2026).",
    "CNN-LSTM (cnn_lstm)": "Same CNN, one unidirectional LSTM layer (hidden width 32) over the 70 columns, mean of outputs. 18,025 parameters.",
    "CNN + temporal convolution (temporal_conv)": "Same CNN, two causal dilated residual Conv1d blocks "
        "(receptive field 13 columns). 17,161 parameters.",
    "CNN + small ViT (hybrid_vit)": "Same CNN, small transformer encoder over the columns with positional "
        "embeddings. 23,881 parameters. Sees the whole row at once.",
    "Signal ResNet1D (resnet1d_wang)": "Reference model on the raw 100 Hz waveforms instead of images. "
        "About 510k parameters. Shows what the image representation costs.",
}
COMMON = ("All models: PTB-XL v1.0.3, official patient folds (1-8 train, 9 validation, 10 test), five overlapping "
          "superclasses (NORM, MI, STTC, CD, HYP), training-only normalization, AdamW lr 1e-3, batch 16, max 20 epochs, "
          "patience 4, cosine schedule, unweighted BCE, no augmentation, no pretrained weights, checkpoint selected "
          "on validation, threshold 0.5, one test inference. Fold 10 was observed before the models were specified, "
          "so test results are exploratory. Intended use: research on ECG-image modelling only, not clinical use. "
          "Known limitations: clean synthetic renderings (no scans/photos), one population (Germany), label noise, "
          "and adaptive page gain on v1 pages leaks amplitude (and therefore hypertrophy) information.")


def get(d, *path):
    for key in path:
        if not isinstance(d, dict) or key not in d:
            return None
        d = d[key]
    return d


def rows():
    for family in FAMILIES:
        for path in sorted((ROOT / "results" / family).glob("*/run.json")):
            run = json.loads(path.read_text(encoding="utf-8"))
            training = run.get("training") or {}
            yield {"family": family, "run": path.parent.name, "seed": run.get("seed", ""),
                   "parameters": get(training, "num_parameters") or run.get("num_parameters") or get(run, "metadata", "num_parameters"),
                   "device": get(training, "device") or get(training, "config", "device") or "cpu",
                   "epochs": get(training, "epochs_run"), "best_epoch": get(training, "best_epoch"),
                   "val": get(run, "metrics", "validation", "macro_roc_auc"), "test": get(run, "metrics", "test", "macro_roc_auc")}


def fmt(value, spec=""):
    return "–" if value is None else format(value, spec)


def main():
    lines = ["# Model cards", "", "Generated by `python -X utf8 -m src.make_model_cards` from completed run records.", "",
             "## Shared facts", "", COMMON, "", "## Models", ""]
    lines += [f"- **{name}.** {text}" for name, text in CARDS.items()]
    lines += ["", "## Every completed run", "",
              "| Family | Run | Seed | Parameters | Device | Epochs (best) | Validation macro AUROC | Test macro AUROC |",
              "|---|---|---:|---:|---|---|---:|---:|"]
    for r in rows():
        lines.append(f"| {r['family']} | {r['run']} | {r['seed']} | {fmt(r['parameters'], ',')} | {r['device']} | "
                     f"{fmt(r['epochs'])} ({fmt(r['best_epoch'])}) | {fmt(r['val'], '.4f')} | {fmt(r['test'], '.4f')} |")
    (ROOT / "docs/model_cards.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote docs/model_cards.md ({len(lines)} lines)")


if __name__ == "__main__":
    main()

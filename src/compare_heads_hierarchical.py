"""Pairwise head comparisons on PTB-XL across seeds (docs/protocol_amendment_2026-11-03.md, section C.2).

Usage:
    python -X utf8 -m src.compare_heads_hierarchical

For the 10 pairs among CNN-only, capacity-matched CNN-only, CNN-LSTM, temporal conv and hybrid ViT (adaptive-gain
pages): mean-over-seeds macro AUROC difference with a hierarchical bootstrap (2,000 resamples, seed 2024; seeds
resampled, then patients, both shared by the two models), two-sided bootstrap p and Holm correction across the 10
pairs. Test (exploratory: fold 10 observed before) and validation are both reported. Primary seed set 42-46
(Mac-CPU seed 42 pooled for the original four networks); sensitivity: GPU-only seeds 43-46.
Reads saved predictions only. Writes results/comparisons/ptbxl_heads_hierarchical/.
"""
from __future__ import annotations

import csv
import itertools

import numpy as np

from src.common import ROOT, write_csv
from src.external_test import CLASS_NAMES, HEADS, hierarchical_difference, holm, macro_auroc

OUT = ROOT / "results/comparisons/ptbxl_heads_hierarchical"
V1 = {"cnn_lstm": "ptbxl_cnn_lstm/ptbxl_cnn_lstm_image_v1_seed42",
      "temporal_conv": "ptbxl_spatiotemporal/ptbxl_spatiotemporal_image_v1_seed42",
      "hybrid_vit": "ptbxl_hybrid_vit/ptbxl_hybrid_vit_image_v1_seed42"}
SEEDS = (42, 43, 44, 45, 46)
LABELS = {"cnn_pool": "CNN-only", "cnn_pool_wide": "CNN-only, capacity-matched", "cnn_lstm": "CNN-LSTM",
          "temporal_conv": "CNN + temporal conv", "hybrid_vit": "CNN + small ViT"}


def run_path(head, seed):
    relative = V1[head] if seed == 42 and head in V1 else f"ptbxl_v2/ptbxl_v2_{head}_seed{seed}"
    return ROOT / "results" / relative


def load(path, split):
    with (path / f"{split}_predictions.csv").open(newline="") as handle:
        rows = list(csv.DictReader(handle))
    return ([r["ecg_id"] for r in rows], [r["patient_id"] for r in rows],
            np.asarray([[int(r[f"truth_{c}"]) for c in CLASS_NAMES] for r in rows]),
            np.asarray([[float(r[f"probability_{c}"]) for c in CLASS_NAMES] for r in rows]))


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    missing = [str(run_path(h, s)) for h in HEADS for s in SEEDS if not (run_path(h, s) / "run.json").exists()]
    if missing:
        raise FileNotFoundError(f"Incomplete runs: {missing}")
    metric = lambda y, p: macro_auroc(y, p, CLASS_NAMES)
    rows, seed_rows = [], []
    for split in ("test", "validation"):
        probabilities, reference = {}, None
        for head in HEADS:
            probabilities[head] = {}
            for s in SEEDS:
                ids, patients, y, p = load(run_path(head, s), split)
                if reference is None:
                    reference = (ids, patients, y)
                elif ids != reference[0] or not np.array_equal(y, reference[2]):
                    raise ValueError(f"{head} seed {s}: {split} records not aligned")
                probabilities[head][s] = p
                seed_rows.append({"partition": split, "model": LABELS[head], "seed": s, "macro_auroc": metric(y, p)})
        ids, patients, y = reference
        groups = {}
        for i, patient in enumerate(patients):
            groups.setdefault(patient, []).append(i)
        clusters = [np.asarray(v) for v in groups.values()]
        for seed_set, seeds in (("42-46 (primary)", list(SEEDS)), ("43-46 GPU only", [43, 44, 45, 46])):
            family = []
            for a, b in itertools.combinations(HEADS, 2):
                result = hierarchical_difference(y, probabilities[a], probabilities[b], metric, seeds, clusters=clusters)
                family.append({"partition": split, "seed_set": seed_set, "comparison": f"{LABELS[b]} minus {LABELS[a]}",
                               **{k: v for k, v in result.items() if k != "seeds"}})
                print(f"{split} {seed_set} {family[-1]['comparison']}: {result['difference']:+.4f} "
                      f"[{result['ci_lower']:+.4f}, {result['ci_upper']:+.4f}]", flush=True)
            for row, adjusted in zip(family, holm([r["p_bootstrap"] for r in family])):
                row["p_holm"], row["significant_at_0.05"] = adjusted, adjusted < 0.05
            rows += family
    write_csv(OUT / "pairwise.csv", rows)
    write_csv(OUT / "per_seed.csv", seed_rows)
    lines = ["# PTB-XL head comparisons across seeds (hierarchical seed x patient bootstrap, Holm over 10 pairs)", "",
             "Generated by `python -X utf8 -m src.compare_heads_hierarchical`. Protocol: docs/protocol_amendment_2026-11-03.md. "
             "Test is exploratory (fold 10 observed before).", "", "## Mean macro AUROC per model (seeds 42-46)", "",
             "| Model | Test mean ± SD | Validation mean ± SD |", "|---|---|---|"]
    for head in HEADS:
        def ms(split):
            v = [r["macro_auroc"] for r in seed_rows if r["partition"] == split and r["model"] == LABELS[head]]
            return f"{np.mean(v):.4f} ± {np.std(v, ddof=1):.4f}"
        lines.append(f"| {LABELS[head]} | {ms('test')} | {ms('validation')} |")
    for split in ("test", "validation"):
        for seed_set in ("42-46 (primary)", "43-46 GPU only"):
            lines += ["", f"## {split.capitalize()}, seeds {seed_set}", "",
                      "| Comparison | Difference [95% CI] | Holm p | Significant |", "|---|---|---:|---|"]
            lines += [f"| {r['comparison']} | {r['difference']:+.4f} [{r['ci_lower']:+.4f}, {r['ci_upper']:+.4f}] | "
                      f"{r['p_holm']:.4f} | {'yes' if r['significant_at_0.05'] else 'no'} |"
                      for r in rows if r["partition"] == split and r["seed_set"] == seed_set]
    (OUT / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
